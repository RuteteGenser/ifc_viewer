let table = en;
export function setLocale(locale) {
  table = locale === "nb" ? { ...en, ...nb } : en;
}
export function t(key, vars = {}) {
  const s = table[key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
